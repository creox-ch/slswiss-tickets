/** Строка для поиска: ключ формы, название расчёта и весь payload. */
function haystack(sub) {
  const parts = [sub?.form_key, sub?.role];
  const p = sub?.payload;
  if (p && typeof p === 'object' && !Array.isArray(p)) {
    for (const [k, v] of Object.entries(p)) {
      parts.push(k);
      if (v != null) parts.push(String(v));
    }
  }
  return parts.filter(Boolean).join(' \n ').toLowerCase();
}

/**
 * Термины для конкретного расчёта — по вхождению в текст или по калькулятору.
 * @param {object} sub заявка (form_key, role, payload)
 * @param {number} limit сколько максимум показывать
 * @returns {{title: string, def: string}[]}
 */
export function glossaryFor(sub, limit = 5) {
  if (!sub || typeof sub !== 'object') return [];
  const text = haystack(sub);
  if (!text) return [];
  const formKey = String(sub.form_key || '').toLowerCase();

  const picked = TERMS.filter(
    (t) => t.tools.includes(formKey) || t.aliases.some((a) => text.includes(a))
  );

  return picked.slice(0, Math.max(0, limit)).map(({ title, def }) => ({ title, def }));
}
