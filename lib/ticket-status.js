/**
 * Переходы статуса билета при подтверждённой оплате.
 *
 * Вынесено из вебхука отдельным модулем ровно по одной причине: внутри роута
 * это условие нельзя протестировать, не подняв Supabase и Payrexx. Здесь —
 * чистая функция, и таблица переходов закрыта юнит-тестами.
 *
 * Статусы билета (см. supabase-schema.sql):
 *   pending → paid → checked_in
 *   pending → failed        (оплата не прошла; позже может пройти повторно)
 *   paid    → refunded      (деньги вернули)
 */

/**
 * Из каких статусов подтверждённая оплата ИМЕЕТ право сделать `paid`.
 *
 * - `pending`  — обычный путь.
 * - `failed`   — человек попробовал ещё раз и на этот раз заплатил. Отказ не
 *                должен запирать заказ навсегда.
 *
 * Остальные намеренно не здесь:
 * - `paid`, `checked_in` — уже обработано. Повторная обработка выдала бы второй
 *   `qr_token` и второе письмо: у покупателя два разных QR, один из которых на
 *   входе не сработает (в БД остаётся последний).
 * - `refunded` — деньги вернули. Поздний или повторно доставленный `confirmed`
 *   не должен воскрешать билет: иначе человек получает рабочий вход за
 *   возвращённые деньги, и чек-ин это не поймает — он увидит честный `paid`.
 */
export const CONFIRMABLE_STATUSES = ['pending', 'failed'];

/**
 * Можно ли по событию `confirmed` перевести билет в `paid`.
 * @param {string|null|undefined} current статус строки в БД
 */
export function canConfirmToPaid(current) {
  return CONFIRMABLE_STATUSES.includes(current);
}
